ALIASES = {"horror": "хоррор", "motivation": "мотивация", "facts": "факты"}


def build(style, theme):
    data = TEMPLATES[style]
    t = data["themes"][theme]
    lines = [f"СЦЕНАРИЙ ({style}): {theme}", "", "ХУК (0–2 сек):", random.choice(t["hook"]), ""]
    for i, block in enumerate(t["blocks"], 1):
        lines += [f"БЛОК {i}:", block, ""]
    lines += ["ФИНАЛ:", data["outro"]]
    return "\n".join(lines)


def fail(parser, message):
    sys.exit(f"{message}\n\n{parser.format_usage()}")


def themes_list(style):
    return ", ".join(TEMPLATES[style]["themes"])


parser = argparse.ArgumentParser(description="Генератор сценариев для коротких видео")
parser.add_argument("style", nargs="?", help="шаблон: " + ", ".join(f"{en}/{ru}" for en, ru in ALIASES.items()))
parser.add_argument("topic", nargs="*", help="тема из списка выбранного шаблона")
args = parser.parse_args()

style = ALIASES.get((args.style or "").lower(), (args.style or "").lower())
if style not in TEMPLATES:
    lines = [f"  {ru} ({en}): {themes_list(ru)}" for en, ru in ALIASES.items()]
    fail(parser, "Укажите шаблон. Доступные шаблоны и темы:\n" + "\n".join(lines))

theme = " ".join(args.topic).strip().lower()
if not theme and sys.stdin.isatty():
    theme = input(f"Тема ({themes_list(style)}): ").strip().lower()
if theme not in TEMPLATES[style]["themes"]:
    shown = f"Тема «{theme}» не найдена" if theme else "Тема не указана"
    fail(parser, f"{shown}. Темы для шаблона «{style}»: {themes_list(style)}\nПример: python script.py {args.style} {next(iter(TEMPLATES[style]['themes']))}")

text = build(style, theme)
out = Path(__file__).resolve().parent / "scenario.txt"
out.write_text(text + "\n", encoding="utf-8")
print(text)
print(f"\nСохранено в {out}")
